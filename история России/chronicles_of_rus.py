class Game:
    def __init__(self):
        pygame.init()
        self.full = "--windowed" not in sys.argv
        try:
            self.screen = pygame.display.set_mode((W, H), pygame.SCALED | (pygame.FULLSCREEN if self.full else pygame.RESIZABLE))
        except pygame.error:
            self.full = False
            self.screen = pygame.display.set_mode((W, H), pygame.SCALED)
        pygame.display.set_caption("Хроники Руси")
        self.clock = pygame.time.Clock()
        fam = "dejavusans,arial,liberationsans,freesans"
        self.f_title = pygame.font.SysFont(fam, 60, bold=True)
        self.f_big = pygame.font.SysFont(fam, 32, bold=True)
        self.f_mid = pygame.font.SysFont(fam, 22)
        self.f_sm = pygame.font.SysFont(fam, 17)
        self.scene = pygame.Surface((W, SH))
        self.fade = pygame.Surface((W, H))
        self.fade.fill((0, 0, 0))
        self.state = "title"
        self.reset()

    def reset(self):
        self.i, self.stage = 0, 0
        self.stats = {"army": 55, "treasury": 55, "people": 55}
        self.result, self.opts, self.lost = [], [], ""
        self.mark()

    def mark(self):
        self.t0 = pygame.time.get_ticks()

    def now(self):
        return pygame.time.get_ticks()

    def typed(self, text, cps=48):
        return int((self.now() - self.t_text) / 1000 * cps), len(text)

    def start_text(self):
        self.t_text = self.now()

    def reveal(self):
        self.t_text = self.now() - 10 ** 6

    def text_done(self, text):
        n, total = self.typed(text)
        return n >= total

    # --- логика ---
    def items(self):
        its = self.all_items()
        return its[self.page * 4:(self.page + 1) * 4] if self.stage in (1, 2) else its

    def pages(self):
        return max(1, (len(self.all_items()) + 3) // 4)

    def all_items(self):
        ev, rf = HISTORY[RULERS[self.i][0]]
        if self.stage == 1:
            return ev
        if not rf:
            return [("", "Реформ провести не успел: правление было слишком коротким или смутным.")]
        return [(y, f"{t} ({NAMES[STATKEY[s[0]]]} {'+' if s[1] == '+' else '−'}2)") for y, t, s in rf]

    def current_text(self):
        r = RULERS[self.i]
        if self.stage == 0:
            return r[3]
        if self.stage == 3:
            return r[4]
        return "\n".join(f"{y} — {t}" if y else t for y, t in self.items())

    def apply_reforms(self):
        for _, _, s in HISTORY[RULERS[self.i][0]][1]:
            k = STATKEY[s[0]]
            self.stats[k] = max(1, min(100, self.stats[k] + (2 if s[1] == "+" else -2)))

    def toggle_full(self):
        self.full = not self.full
        flags = pygame.SCALED | (pygame.FULLSCREEN if self.full else pygame.RESIZABLE)
        self.screen = pygame.display.set_mode((W, H), flags)

    def advance(self):
        if self.state == "title":
            self.state = "scene"
            self.enter_ruler()
        elif self.state == "scene":
            if not self.text_done(self.current_text()):
                self.reveal()
            elif self.stage in (1, 2) and self.page + 1 < self.pages():
                self.page += 1
                self.start_text()
            elif self.stage < 3:
                self.stage += 1
                self.page = 0
                if self.stage == 2:
                    self.apply_reforms()
                self.start_text()
            else:
                self.state = "choice"
                self.opts = random.sample(OPTIONS[RULERS[self.i][6]], 3)
        elif self.state == "result":
            self.i += 1
            if self.i >= len(RULERS):
                self.state = "end"
            else:
                self.state = "scene"
                self.enter_ruler()
        elif self.state in ("end", "lost"):
            self.reset()
            self.state = "scene"
            self.enter_ruler()

    def enter_ruler(self):
        self.stage = 0
        self.page = 0
        self.mark()
        self.start_text()

    def choose(self, k):
        if self.state != "choice" or not 0 <= k < 3:
            return
        _, da, dt, dp = self.opts[k]
        delta = {"army": da + 1, "treasury": dt + 1, "people": dp + 1}
        self.event_text = ""
        if random.random() < .3:
            name, key = random.choice(MISFORTUNES)
            delta[key] -= 8
            self.event_text = f"{name}: {NAMES[key]} −8"
        for key, d in delta.items():
            self.stats[key] = min(100, self.stats[key] + d)
        self.delta = delta
        bad = [NAMES[k2] for k2, v in self.stats.items() if v <= 0]
        if bad:
            self.lost = f"{bad[0]} иссякла, и династия пала при правителе {RULERS[self.i][0]}."
            self.state = "lost"
        else:
            self.state = "result"

    def option_rect(self, k):
        return pygame.Rect(190, PY + 54 + k * 46, W - 220, 40)

    # --- отрисовка ---
    def hud(self):
        pygame.draw.rect(self.screen, (8, 14, 28), (0, 0, W, HUD))
        for k, (key, label, col) in enumerate(STATS):
            x = 14 + k * 190
            self.screen.blit(self.f_sm.render(label, True, PAPER), (x, 12))
            rect(self.screen, (40, 50, 72), x + 64, 15, 100, 14)
            rect(self.screen, col, x + 64, 15, max(1, self.stats[key]), 14)
        r = RULERS[min(self.i, len(RULERS) - 1)]
        txt = self.f_sm.render(f"{r[1]} г.  ·  {self.i + 1}/{len(RULERS)}", True, GOLD)
        self.screen.blit(txt, (W - txt.get_width() - 14, 12))
        rect(self.screen, GOLD, 0, HUD - 3, W * (self.i + 1) / len(RULERS), 3)

    def panel(self):
        r = RULERS[self.i]
        pygame.draw.rect(self.screen, INK, (0, PY, W, H - PY))
        rect(self.screen, GOLD, 0, PY, W, 3)
        bust(self.screen, 95, PY + 100, r[1], self.i)
        x, w = 190, W - 220
        if self.state == "scene":
            n, _ = self.typed(self.current_text())
            if self.stage == 0:
                self.screen.blit(self.f_big.render(r[0], True, GOLD), (x, PY + 14))
                self.screen.blit(self.f_sm.render(r[2], True, (160, 176, 200)), (x, PY + 54))
                draw_text(self.screen, self.f_mid, r[3], PAPER, x, PY + 86, w, n)
            elif self.stage in (1, 2):
                title = "События" if self.stage == 1 else "Реформы"
                self.screen.blit(self.f_big.render(f"{r[0]}: {title.lower()}" + (f"  {self.page + 1}/{self.pages()}" if self.pages() > 1 else ""), True, GOLD), (x, PY + 10))
                self.draw_list(self.items(), x, PY + 56, w, n)
            else:
                circ(self.screen, GOLD, x + 10, PY + 30, 9)
                rect(self.screen, GOLD, x + 6, PY + 40, 8, 5)
                self.screen.blit(self.f_big.render("Курьёз", True, GOLD), (x + 30, PY + 12))
                draw_text(self.screen, self.f_mid, r[4], PAPER, x, PY + 66, w, n)
            hint = "Пробел — дальше  ·  F11 — полный экран"
        elif self.state == "choice":
            self.screen.blit(self.f_mid.render(CRISIS[r[6]], True, GOLD), (x, PY + 14))
            mx, my = pygame.mouse.get_pos()
            for k, o in enumerate(self.opts):
                rc = self.option_rect(k)
                pygame.draw.rect(self.screen, (44, 62, 100) if rc.collidepoint(mx, my) else (28, 42, 72), rc, border_radius=6)
                self.screen.blit(self.f_mid.render(f"{k + 1}.  {o[0]}", True, PAPER), (rc.x + 12, rc.y + 8))
            hint = "Нажмите 1, 2 или 3"
        else:
            self.screen.blit(self.f_big.render("Решение принято", True, GOLD), (x, PY + 14))
            for k, (key, label, col) in enumerate(STATS):
                d = self.delta[key]
                c = (110, 220, 140) if d >= 0 else (255, 120, 120)
                self.screen.blit(self.f_mid.render(f"{label} {d:+d}".replace("-", "−"), True, c), (x + k * 190, PY + 70))
            if self.event_text:
                self.screen.blit(self.f_mid.render("Беда! " + self.event_text, True, (255, 170, 90)), (x, PY + 118))
            hint = "Пробел — следующий правитель"
        h = self.f_sm.render(hint, True, (130, 146, 175))
        self.screen.blit(h, (W - h.get_width() - 16, H - 28))

    def draw_list(self, items, x, y, w, n):
        f = self.f_sm
        for yr, tx in items:
            if n <= 0:
                break
            head = f"{yr} — " if yr else ""
            hw = f.size(head)[0] if head else 0
            if head:
                self.screen.blit(f.render(head[:n], True, GOLD), (x, y))
            left, yy = n - len(head), y
            for ln in wrap(f, tx, w - hw):
                if left <= 0:
                    break
                self.screen.blit(f.render(ln[:left], True, PAPER), (x + hw, yy))
                left -= len(ln) + 1
                yy += f.get_linesize()
            y = max(yy, y + f.get_linesize()) + 5
            n -= len(head) + len(tx) + 1

    def banner(self, title, lines, col):
        dim = pygame.Surface((W, H))
        dim.set_alpha(190)
        dim.fill((6, 10, 22))
        self.screen.blit(dim, (0, 0))
        t = self.f_title.render(title, True, col)
        self.screen.blit(t, ((W - t.get_width()) // 2, 150))
        y = 250
        for ln in lines:
            for part in wrap(self.f_mid, ln, 700):
                tx = self.f_mid.render(part, True, PAPER)
                self.screen.blit(tx, ((W - tx.get_width()) // 2, y))
                y += 32

    def draw(self):
        t = (self.now() - self.t0) / 1000
        self.screen.fill(INK)
        kind = "kremlin" if self.state == "title" else RULERS[min(self.i, len(RULERS) - 1)][5]
        SCENES[kind](self.scene, t)
        self.screen.blit(self.scene, (0, HUD))
        if self.state == "title":
            self.banner("ХРОНИКИ РУСИ", ["От Рюрика до наших дней", "Ведите династию через века: следите за армией, казной и народом.",
                                         "Пробел — начать  ·  F11 — полный экран"], GOLD)
        else:
            self.hud()
            if self.state in ("scene", "choice", "result"):
                self.panel()
            elif self.state == "lost":
                self.banner("Династия пала", [self.lost, "Пробел — начать заново"], (255, 120, 120))
            else:
                self.banner("Хроника завершена", [f"Вы провели династию через {len(RULERS)} правителей.",
                                                   "Армия {army}, казна {treasury}, народ {people}.".format(**self.stats),
                                                   "Пробел — сыграть снова"], GOLD)
            if self.state == "scene" and t < .7:
                self.fade.set_alpha(int(255 * (1 - t / .7)))
                self.screen.blit(self.fade, (0, 0))
        pygame.display.flip()

    def run(self):
        while True:
            for e in pygame.event.get():
                if e.type == pygame.QUIT or (e.type == pygame.KEYDOWN and e.key == pygame.K_ESCAPE):
                    pygame.quit()
                    sys.exit()
                if e.type == pygame.KEYDOWN:
                    if e.key == pygame.K_F11:
                        self.toggle_full()
                    elif e.key in (pygame.K_1, pygame.K_2, pygame.K_3):
                        self.choose(e.key - pygame.K_1)
                    elif e.key in (pygame.K_SPACE, pygame.K_RETURN) and self.state != "choice":
                        self.advance()
                if e.type == pygame.MOUSEBUTTONDOWN and e.button == 1:
                    if self.state == "choice":
                        for k in range(3):
                            if self.option_rect(k).collidepoint(e.pos):
                                self.choose(k)
                    else:
                        self.advance()
            self.draw()
            self.clock.tick(60)


if __name__ == "__main__":
    Game().run()
